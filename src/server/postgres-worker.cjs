function translate(sql,schema) {
  sql=sql.replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g,"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").replace(/\bINTEGER\b/g,"BIGINT").replace(/\bREAL\b/g,"DOUBLE PRECISION").replace(/\bBLOB\b/g,"BYTEA");
  sql=sql.replace(/CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\)(;|$)/g,(_all,table,body,end)=>`CREATE TABLE IF NOT EXISTS ${table} (${body}, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY)${end}`);
  sql=sql.replace(/\bPRAGMA table_info\((\w+)\)/g,(_all,table)=>`SELECT column_name AS name FROM information_schema.columns WHERE table_schema='${schema}' AND table_name='${table}' ORDER BY ordinal_position`);
  sql=sql.replace(/\bsqlite_master\b/g,`(SELECT table_name AS name,'table' AS type FROM information_schema.tables WHERE table_schema='${schema}') AS sqlite_master`);
  sql=sql.replace(/json_extract\((\w+),'\$\.(\w+)'\)/g,"($1::jsonb->>'$2')");
  // Quote the existing camelCase projection aliases, since Postgres otherwise folds them.
  sql=sql.replace(/\b(AS\s+)?([a-z][a-zA-Z]*[A-Z][a-zA-Z]*)\b(?=\s*(?:,|FROM\b|$))/g,(all,as,name)=>`${as||""}"${name}"`);
  sql=sql.replace(/\b(FROM|JOIN|INTO|REFERENCES|TABLE(?: IF NOT EXISTS)?)\s+([a-z_][a-z0-9_]*)(?![\w.])/gi,(all,verb,table)=>tables.has(table)?`${verb} ${ident(schema)}.${ident(table)}`:all);
  sql=sql.replace(/\bUPDATE\s+([a-z_][a-z0-9_]*)\s+SET\b/gi,(all,table)=>tables.has(table)?`UPDATE ${ident(schema)}.${ident(table)} SET`:all);
  return sql;
}
async function columns(client,schema,table) {
  const key=`${schema}.${table}`;
  if(!columnCache.has(key))columnCache.set(key,(await client.query("SELECT column_name FROM information_schema.columns WHERE table_schema=$1 AND table_name=$2 AND column_name!='rowid' ORDER BY ordinal_position",[schema,table])).rows.map(r=>r.column_name));
  return columnCache.get(key);
}
async function query(client,state,raw,args,mode) {
  const ignore=/^\s*INSERT OR IGNORE/i.test(raw),replace=/^\s*INSERT OR REPLACE/i.test(raw);
  let sql=raw.replace(/^\s*INSERT OR (IGNORE|REPLACE)/i,"INSERT");
  const implicit=sql.match(/^\s*INSERT INTO (\w+) VALUES/i);
  if(implicit)sql=sql.replace(/INSERT INTO (\w+) VALUES/i,`INSERT INTO $1 (${(await columns(client,state.namespace,implicit[1])).map(ident).join(",")}) VALUES`);
  if(ignore)sql=sql.replace(/;?\s*$/," ON CONFLICT DO NOTHING");
  if(replace) {
    if(!/^INSERT INTO memberships\b/i.test(sql))throw Error("Unsupported legacy replacement statement.");
    sql+=" ON CONFLICT(account_id,owner_id,case_id) DO UPDATE SET member_id=EXCLUDED.member_id,email=EXCLUDED.email";
  }
  sql=translate(sql,state.namespace);
  let index=0;sql=sql.replace(/\?/g,()=>`$${++index}`);
  const insert=/^\s*INSERT\b/i.test(sql);
  if(mode==="run" && insert && !/\bRETURNING\b/i.test(sql))sql+=" RETURNING *";
  const result=await client.query(sql,args.map(v=>v instanceof Uint8Array?Buffer.from(v):v));
  if(mode==="run")return {changes:result.rowCount??0,lastInsertRowid:result.rows[0]?.seq??(typeof result.rows[0]?.id==="number"?result.rows[0].id:0)};
  return mode==="get"?result.rows[0]:result.rows;
}
async function withClient(state,run,write=false) {
  if(state.client)return run(state.client);
  const client=await pool.connect();
  try {
    if(write)await client.query("BEGIN; SELECT pg_advisory_xact_lock(hashtextextended('"+state.namespace+"',0))");
    const value=await run(client);
    if(write)await client.query("COMMIT");
    return value;
  }catch(error){if(write)await client.query("ROLLBACK");throw error;}finally{client.release();}
}
async function handle(m) {
  if(m.action==="open") {
    ident(m.namespace);
    if(!initialised.has(m.namespace)) {
      const client=await pool.connect();
      try {
        await client.query("BEGIN; SELECT pg_advisory_xact_lock(hashtextextended('"+m.namespace+"',0))");
        await client.query(`CREATE SCHEMA IF NOT EXISTS ${ident(m.namespace)}; REVOKE ALL ON SCHEMA ${ident(m.namespace)} FROM PUBLIC, anon, authenticated; ALTER DEFAULT PRIVILEGES IN SCHEMA ${ident(m.namespace)} REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;`);
        await client.query("COMMIT");
        initialised.add(m.namespace);
      }catch(error){await client.query("ROLLBACK");throw error;}finally{client.release();}
    }
    sessions.set(m.id,{namespace:m.namespace,depth:0,pendingDdl:new Set()});return null;
  }
  const state=sessions.get(m.id);if(!state)throw Error("Database connection is closed.");
  if(m.action==="close") {if(state.client){await state.client.query("ROLLBACK");state.client.release();}sessions.delete(m.id);return null;}
  if(m.action==="begin") {
    if(state.depth===0){state.client=await pool.connect();try{await state.client.query("BEGIN; SELECT pg_advisory_xact_lock(hashtextextended('"+state.namespace+"',0))");}catch(error){state.client.release(error);delete state.client;throw error;}}
    else await state.client.query(`SAVEPOINT nested_${state.depth}`);
    state.depth++;return null;
  }
  if(m.action==="commit"||m.action==="rollback") {
    state.depth--;
    if(state.depth===0){try{await state.client.query(m.action==="commit"?"COMMIT":"ROLLBACK");if(m.action==="commit")for(const key of state.pendingDdl)ddlCache.add(key);}finally{state.pendingDdl.clear();state.client.release();delete state.client;}}
    else await state.client.query(m.action==="commit"?`RELEASE SAVEPOINT nested_${state.depth}`:`ROLLBACK TO SAVEPOINT nested_${state.depth}`);
    if(m.action==="rollback") {
      state.pendingDdl.clear();
      for(const key of columnCache.keys())if(key.startsWith(state.namespace+"."))columnCache.delete(key);
    }
    return null;
  }
  if(m.action==="exec") {
    const cacheKey=state.namespace+":"+m.sql;
    if(/^\s*CREATE TABLE IF NOT EXISTS/.test(m.sql) && ddlCache.has(cacheKey))return null;
    await withClient(state,async client=>{
      await client.query(translate(m.sql,state.namespace));
      const names=[...m.sql.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map(x=>x[1]);
      for(const name of names)await client.query(`ALTER TABLE ${ident(state.namespace)}.${ident(name)} ENABLE ROW LEVEL SECURITY; REVOKE ALL ON TABLE ${ident(state.namespace)}.${ident(name)} FROM PUBLIC, anon, authenticated;`);
      for(const key of columnCache.keys())if(key.startsWith(state.namespace+"."))columnCache.delete(key);
    },true);
    if(/^\s*CREATE TABLE IF NOT EXISTS/.test(m.sql))(state.depth?state.pendingDdl:ddlCache).add(cacheKey);
    return null;
  }
  return withClient(state,client=>query(client,state,m.sql,m.args,m.mode),m.mode==="run");
}
parentPort.on("message",async m=>{
  try {m.reply.postMessage({ok:true,value:await handle(m)});}
  catch(error){m.reply.postMessage({ok:false,error:error.message,code:error.code});}
  finally{Atomics.store(m.signal,0,1);Atomics.notify(m.signal,0);m.reply.close();}
});

const pool=new Pool({host:url.hostname,port:Number(url.port||5432),user:decodeURIComponent(url.username),password:decodeURIComponent(url.password),database:url.pathname.slice(1)||"postgres",ssl:{ca,rejectUnauthorized:true},max:4,connectionTimeoutMillis:10000,query_timeout:60000,application_name:"guardian"});
